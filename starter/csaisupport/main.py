@tool
def calculate_loyalty_discount(
    loyalty_points: int,
    tier: str,
    order_total: float,
    product_category: str = "standard",
) -> str:
    """
    Calculate the loyalty discount for a customer order using the
    AgentCore Code Interpreter. Runs exact arithmetic in a secure sandbox.

    Args:
        loyalty_points: Customer's current points balance
        tier: Customer tier ??? Silver, Gold, or Platinum
        order_total: Order total in USD
        product_category: standard, device, or fresh

    Returns:
        Full discount breakdown and final price
    """

    code = f"""
import json
import math

loyalty_points = {int(loyalty_points)}
tier = {json.dumps(tier)}
order_total = {float(order_total)}
product_category = {json.dumps(product_category)}

earn_rates = {{
    "standard": 1,
    "device": 2,
    "fresh": 5
}}

tier_rates = {{
    "Silver": 0.00,
    "Gold": 0.10,
    "Platinum": 0.15
}}

points_redeemed = min(
    (loyalty_points // 500) * 500,
    int((order_total * 0.50) * 100)
)

points_discount = points_redeemed / 100

subtotal_after_points = max(
    0,
    order_total - points_discount
)

tier_discount = subtotal_after_points * tier_rates.get(tier, 0.0)

final_total = max(
    0,
    subtotal_after_points - tier_discount
)

total_savings = order_total - final_total

points_earned = math.floor(
    final_total * earn_rates.get(product_category, 1)
)

remaining_points = loyalty_points - points_redeemed

result = {{
    "original_total": round(order_total, 2),
    "points_redeemed": points_redeemed,
    "points_discount": round(points_discount, 2),
    "tier": tier,
    "tier_discount_rate": tier_rates.get(tier, 0.0),
    "tier_discount": round(tier_discount, 2),
    "final_total": round(final_total, 2),
    "total_savings": round(total_savings, 2),
    "points_earned": points_earned,
    "remaining_points": remaining_points
}}

print(json.dumps(result))
"""

    try:
        with code_session(REGION) as code_client:
            response = code_client.invoke(
                "executeCode",
                {
                    "code": code,
                    "language": "python",
                    "clearContext": True,
                },
            )

            for event in response["stream"]:
                if "result" in event:
                    return json.dumps(event["result"])

        return json.dumps(
            {
                "error": "Code Interpreter returned no result."
            }
        )

    except Exception as exc:
        logger.warning(
            "Code Interpreter unavailable: %s",
            exc,
        )

        tier_rates = {
            "Silver": 0.00,
            "Gold": 0.10,
            "Platinum": 0.15,
        }

        rate = tier_rates.get(tier, 0.0)
        tier_discount = order_total * rate
        final_total = order_total - tier_discount

        fallback = {
            "original_total": round(order_total, 2),
            "points_redeemed": 0,
            "points_discount": 0.00,
            "tier": tier,
            "tier_discount_rate": rate,
            "tier_discount": round(tier_discount, 2),
            "final_total": round(final_total, 2),
            "total_savings": round(tier_discount, 2),
            "points_earned": int(
                final_total
                * {
                    "standard": 1,
                    "device": 2,
                    "fresh": 5,
                }.get(product_category, 1)
            ),
            "remaining_points": loyalty_points,
            "fallback": True,
        }

        return json.dumps(fallback)



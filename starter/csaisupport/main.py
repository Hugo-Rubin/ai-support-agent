class MemoryHook(HookProvider):
    """Long-term memory hook for the customer support agent."""

    def __init__(
        self,
        actor_id: str,
        session_id: str,
        memory_client: MemoryClient,
        memory_id: str,
    ):
        self.actor_id = actor_id
        self.session_id = session_id
        self.memory_client = memory_client
        self.memory_id = memory_id
        self.namespaces = get_namespaces(memory_client, memory_id)

    @staticmethod
    def _text_from_message(message) -> str:
        """Extract plain text from a Strands message."""
        content = message.get("content", []) if isinstance(message, dict) else []

        texts = []

        for block in content:
            if isinstance(block, dict) and "text" in block:
                texts.append(block["text"])

        return "\n".join(texts).strip()

    def retrieve_customer_context(self, event: MessageAddedEvent):
        """Retrieve relevant memories and prepend them to the user message."""

        message = event.message

        if not isinstance(message, dict):
            return

        if message.get("role") != "user":
            return

        text = self._text_from_message(message)

        if not text:
            return

        memories = []

        for strategy_type, namespace_template in self.namespaces.items():
            namespace = namespace_template.format(
                actorId=self.actor_id
            )

            try:
                results = self.memory_client.retrieve_memories(
                    memory_id=self.memory_id,
                    namespace=namespace,
                    query=text,
                    top_k=5,
                )

                for result in results or []:
                    memory_text = (
                        result.get("content", {}).get("text")
                        if isinstance(result, dict)
                        else None
                    )

                    if memory_text:
                        memories.append(
                            f"[{strategy_type}] {memory_text}"
                        )

            except Exception as exc:
                logger.warning(
                    "Memory retrieval failed for %s: %s",
                    strategy_type,
                    exc,
                )

        if memories:
            message["content"] = [
                {
                    "text": (
                        "Customer Context:\n"
                        + "\n".join(memories)
                        + "\n\n"
                        + text
                    )
                }
            ]

    def save_support_interaction(self, event: AfterInvocationEvent):
        """Save the completed turn to memory after the agent responds."""

        messages = event.agent.messages

        customer_query = None
        agent_response = None

        for message in reversed(messages):
            if not isinstance(message, dict):
                continue

            role = message.get("role")
            text = self._text_from_message(message)

            if not text:
                continue

            if agent_response is None and role == "assistant":
                agent_response = text
                continue

            if customer_query is None and role == "user":
                customer_query = text
                break

        if customer_query and agent_response:
            try:
                self.memory_client.create_event(
                    memory_id=self.memory_id,
                    actor_id=self.actor_id,
                    session_id=self.session_id,
                    messages=[
                        (customer_query, "USER"),
                        (agent_response, "ASSISTANT"),
                    ],
                )
            except Exception as exc:
                logger.warning(
                    "Failed to save interaction to memory: %s",
                    exc,
                )

    def register_hooks(self, registry: HookRegistry) -> None:
        """Register both memory callbacks."""

        registry.add_callback(
            MessageAddedEvent,
            self.retrieve_customer_context,
        )

        registry.add_callback(
            AfterInvocationEvent,
            self.save_support_interaction,
        )



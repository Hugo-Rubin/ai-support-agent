@app.entrypoint
async def invoke(payload, context=None):
    """
    Main handler called by AgentCore for every incoming request.

    Expected payload keys:
        prompt      (str, required)
        customer_id (str, optional)
        session_id  (str, optional)
    """

    try:
        user_input = payload.get("prompt", "")
        actor_id = payload.get("customer_id", "anonymous")
        session_id = payload.get("session_id") or str(uuid.uuid4())

        if not user_input:
            return "Please provide a customer support question."

        memory_hook = MemoryHook(
            actor_id=actor_id,
            session_id=session_id,
            memory_client=memory_client,
            memory_id=MEMORY_ID,
        )

        agent_core_browser = AgentCoreBrowser(
            region=REGION,
        )

        tools = [
            search_knowledge_base,
            calculate_loyalty_discount,
            agent_core_browser.browser,
        ]

        gateway_client = MCPClient(
            lambda: streamable_http_client(GATEWAY_URL)
        )

        with gateway_client:
            gateway_tools = gateway_client.list_tools_sync()
            tools.extend(gateway_tools)

            system_prompt = """
You are a helpful Amazon customer support AI agent.

Your responsibilities are:
- Help customers with product questions.
- Look up customer and order information using the Gateway tools.
- Explain order statuses accurately.
- Help with returns and refunds using the appropriate Gateway tools.
- Use the knowledge base for product specifications, policies,
  warranties, loyalty information, and order status definitions.
- Use the loyalty discount calculator when calculating discounts.
- Use browser tools when web browsing is genuinely necessary.
- Use customer context from memory when it is relevant.
- Never invent order, customer, product, refund, or policy information.
- Clearly explain what you found and what action was taken.
"""

            agent = Agent(
                model=model,
                tools=tools,
                system_prompt=system_prompt,
                hooks=[memory_hook],
            )

            response = agent(user_input)

            if hasattr(response, "message"):
                message = response.message
            else:
                message = response

            content = message.get("content", [])

            if content:
                first_block = content[0]

                if isinstance(first_block, dict):
                    return first_block.get(
                        "text",
                        str(first_block),
                    )

                return str(first_block)

            return str(response)

    except Exception as exc:
        logger.exception("Agent invocation failed")
        return f"Sorry, I encountered an error while processing your request: {exc}"


